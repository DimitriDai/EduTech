"""
services/match_service.py

职责：
- 输入：words(list[str]) + selected_fields(list[str]) + cache_mode
- 输出：每个 word 对应一个选中的 Entry（可能字段不全） + missing_fields
- 规则：
  1) 优先 global_cache 命中且满足字段
  2) 否则查 uploaded_vocab_cache：多 entry 用 tie-break 选 best
  3) 都不满足则标记 need_enrich（并返回缺失字段）
- 写回策略：
  - USE_CACHE：只填空，不覆盖已有值
  - FORCE_OVERWRITE：整条覆盖（作为“强制重生成”）
  - TEMP_ONLY：仅本次生效，不写回 global_cache
"""

