@dataclass
class MatchResultItem:
    word_original: str
    word_norm: str
    entry: Entry
    source_stage: str         # global_cache / uploaded_vocab / need_enrich
    missing_fields: List[str]
    chosen_rule: str          # debug 用


# =========================
# MatchService
# =========================

@dataclass
class CacheStores:
    global_cache_path: str
    uploaded_vocab_cache_path: str


class MatchService:
    def __init__(self, stores: CacheStores):
        # print("[STORES_ATTRS]", [a for a in dir(stores) if not a.startswith("_")])
        # print("[STORES_DICT]", getattr(stores, "__dict__", None))
        self.global_repo = CacheRepo(stores.global_cache_path)
        self.uploaded_repo = CacheRepo(stores.uploaded_vocab_cache_path)

    def match_words(
        self,
        words: List[str],
        selected_fields: List[str],
        cache_mode: str = CacheMode.USE_CACHE,
    ) -> List[MatchResultItem]:

        # 防御：过滤非法字段
        selected_fields = [f for f in selected_fields if f in VALID_FIELDS]

        results: List[MatchResultItem] = []

        for w in words:
            w0 = (w or "").strip()
            if not w0:
                continue
            wn = norm_word(w0)

            # 1) global_cache 命中：优先返回“满足字段”的 entry
            g = self.global_repo.get_group(wn)
            if g and g.entries:
                satisfying = [e for e in g.entries if entry_satisfies_fields(e, selected_fields)]
                if satisfying:
                    chosen = satisfying[0] if len(satisfying) == 1 else pick_best_entry(satisfying)
                    results.append(MatchResultItem(
                        word_original=w0,
                        word_norm=wn,
                        entry=chosen,
                        source_stage="global_cache",
                        missing_fields=[],
                        chosen_rule="cache_hit_satisfy",
                    ))
                    continue

                # 命中但不满足：先拿一个 best 当 base，再去 uploaded 看是否更好
                chosen_from_cache = g.entries[0] if len(g.entries) == 1 else pick_best_entry(g.entries)
            else:
                chosen_from_cache = None

            # 2) 查 uploaded_vocab_cache
            u = self.uploaded_repo.get_group(wn)
            if u and u.entries:
                chosen_from_uploaded = u.entries[0] if len(u.entries) == 1 else pick_best_entry(u.entries)

                # 如果 cache 也有 entry：选“缺得更少”的；缺一样则 tie-break
                if chosen_from_cache is not None:
                    miss_cache = get_missing_fields(chosen_from_cache, selected_fields)
                    miss_up = get_missing_fields(chosen_from_uploaded, selected_fields)

                    if len(miss_up) < len(miss_cache):
                        chosen = chosen_from_uploaded
                        chosen_rule = "uploaded_better"
                    elif len(miss_up) > len(miss_cache):
                        chosen = chosen_from_cache
                        chosen_rule = "cache_kept"
                    else:
                        chosen = pick_best_entry([chosen_from_cache, chosen_from_uploaded])
                        chosen_rule = "tie_cache_vs_uploaded"
                else:
                    chosen = chosen_from_uploaded
                    chosen_rule = "uploaded_only"

                miss = get_missing_fields(chosen, selected_fields)

                # match 阶段不写回 global_cache（由 enrich 阶段统一写回）

                if not miss:
                    results.append(MatchResultItem(
                        word_original=w0,
                        word_norm=wn,
                        entry=chosen,
                        source_stage="uploaded_vocab",
                        missing_fields=[],
                        chosen_rule=chosen_rule,
                    ))
                else:
                    results.append(MatchResultItem(
                        word_original=w0,
                        word_norm=wn,
                        entry=chosen,
                        source_stage="need_enrich",
                        missing_fields=miss,
                        chosen_rule=chosen_rule,
                    ))
                continue

            # 3) uploaded 也没命中：need_enrich（构造最小 entry）
            if chosen_from_cache is not None:
                chosen = chosen_from_cache
                chosen_rule = "cache_hit_not_satisfy_no_uploaded"
            else:
                chosen = Entry(word_original=w0, word_norm=wn, source="need_enrich", meta={})
                chosen_rule = "no_hit"

            miss = get_missing_fields(chosen, selected_fields)

            # match 阶段不写回 global_cache
            results.append(MatchResultItem(
                word_original=w0,
                word_norm=wn,
                entry=chosen,
                source_stage="need_enrich" if miss else "global_cache",
                missing_fields=miss,
                chosen_rule=chosen_rule,
            ))

        # match 阶段不写回 global_cache
        # 写回统一由 enrich_service 完成
        pass
        
        return results

    def _write_back(self, wn: str, entry: Entry, selected_fields: List[str], cache_mode: str) -> None:
        if cache_mode == CacheMode.TEMP_ONLY:
            return

        group = self.global_repo.get_group(wn)
        if not group:
            group = WordEntryGroup(word_norm=wn, word_display=entry.word_original, entries=[])

        # 简化策略：global_cache 每个 word 只维护一条“主 entry”（entries[0]）
        if not group.entries:
            group.entries.append(entry)
            self.global_repo.upsert_group(group)
            return

        existing = group.entries[0]

        if cache_mode == CacheMode.FORCE_OVERWRITE:
            group.entries[0] = overwrite_entry(existing, entry)
        else:
            group.entries[0] = merge_fill_blanks(existing, entry, selected_fields)

        self.global_repo.upsert_group(group)


