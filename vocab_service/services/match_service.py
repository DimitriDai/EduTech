# =========================
# CacheMode（前端勾选映射）
# =========================

class CacheMode:
    USE_CACHE = "USE_CACHE"               # 默认：允许写回填空
    FORCE_OVERWRITE = "FORCE_OVERWRITE"   # 强制重生成（写回覆盖）
    TEMP_ONLY = "TEMP_ONLY"               # 仅本次生效（不写回）


# =========================
# 字段集合（和 entry_schema 对齐）
# =========================
VALID_FIELDS = {
    "word_original",
    "word_norm",
    "phonetic_uk",
    "phonetic_us",
    "pos_cn",
    "definition_en",
    "example",
    "example_cn",
    "synonyms",
    # audio
    "audio_uk",
    "audio_us",
    "audio_primary",
}

ALLOWED_COUNTS = {15, 20, 25, 30, 50}

# ---- audio fields: system-level fields (NOT generated by DS) ----
AUDIO_FIELDS = {"audio_uk", "audio_us", "audio_primary"}

def norm_word(s: str) -> str:
    s = (s or "").strip()
    s = re.sub(r"\s+", " ", s)
    return s.lower()


def _has_value(v: Any) -> bool:
    if v is None:
        return False
    if isinstance(v, str):
        return v.strip() != ""
    if isinstance(v, list):
        return len(v) > 0
    if isinstance(v, dict):
        return len(v) > 0
    return True


def entry_satisfies_fields(entry: Entry, selected_fields: List[str]) -> bool:
    for f in selected_fields:
        if f not in VALID_FIELDS:
            continue
        if not _has_value(getattr(entry, f, None)):
            return False
    return True
def get_missing_fields(entry, selected_fields):
    """
    entry 可能是：
    - dict
    - dataclass / 普通对象（属性访问）
    - pydantic BaseModel（model_dump）
    这里统一用“安全取值”，避免 entry.get 报错。
    """
    def _get_val(obj, key, default=""):
        if obj is None:
            return default

        # dict
        if isinstance(obj, dict):
            return obj.get(key, default)

        # pydantic v2
        if hasattr(obj, "model_dump") and callable(getattr(obj, "model_dump")):
            try:
                d = obj.model_dump()
                if isinstance(d, dict):
                    return d.get(key, default)
            except Exception:
                pass

        # pydantic v1
        if hasattr(obj, "dict") and callable(getattr(obj, "dict")):
            try:
                d = obj.dict()
                if isinstance(d, dict):
                    return d.get(key, default)
            except Exception:
                pass

        # 普通对象属性
        return getattr(obj, key, default)

    miss = []
    for f in selected_fields:
        v = _get_val(entry, f, "")
        if v is None:
            miss.append(f)
        elif isinstance(v, str):
            if not v.strip():
                miss.append(f)
        elif isinstance(v, list):
            if len(v) == 0:
                miss.append(f)
        else:
            # 其他类型：0/False 一般不算缺失，这里不动
            pass

    return miss

# =========================
# JSON Repo（支持坏文件/空文件）
# =========================

def load_json_safely(path: str) -> Dict[str, Any]:
    if not os.path.exists(path):
        return {}
    try:
        if os.path.getsize(path) == 0:
            return {}
    except OSError:
        pass
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError:
        return {}
    except Exception:
        return {}


def save_json_atomically(path: str, data: Dict[str, Any]) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    os.replace(tmp, path)

class CacheRepo:
    """
    JSON 结构：
      repo[word_norm] = {
        "word_norm": "...",
        "word_display": "...",
        "entries": [EntryDict, ...]
      }
    """

    def __init__(self, path: str):
        self.path = path
        self.data: Dict[str, Any] = load_json_safely(path)
        # 只记录本次真正改动过的 key，避免用旧内存覆盖别人新写入的数据
        self._dirty_keys: set[str] = set()

    def get_group(self, wn: str) -> Optional[WordEntryGroup]:
        raw = self.data.get(wn)
        if not raw:
            return None
        try:
            return WordEntryGroup.from_dict(raw)
        except Exception:
            return None

    def upsert_group(self, group: WordEntryGroup) -> None:
        self.data[group.word_norm] = group.to_dict()
        self._dirty_keys.add(group.word_norm)


    def save(self) -> None:
        """
        上线安全版写回：
        - 跨请求/跨进程加锁：同一时刻只有一个写者
        - 保留 dirty-merge：只写本次改动的 key，降低覆盖风险
        - 仍使用原子写：tmp -> replace，避免半文件
        """
        if not self._dirty_keys:
            return

        lock_path = self.path + ".lock"

        with file_lock(lock_path, timeout=60.0, poll=0.05):
            # 锁内重新读盘：避免用旧内存覆盖别人刚写入的数据
            disk_data = load_json_safely(self.path)

            # 只把本次改动过的 key 写入磁盘数据
            for k in self._dirty_keys:
                if k in self.data:
                    disk_data[k] = self.data[k]

            print(f"[CACHE_WRITE] path={self.path} dirty_keys={len(self._dirty_keys)} lock={lock_path}")
            save_json_atomically(self.path, disk_data)

            # 更新内存快照
            self.data = disk_data
            self._dirty_keys.clear()

# =========================
# 多 entry tie-break（按你需求案）
# =========================

def pick_best_entry(entries: List[Entry]) -> Entry:
    """
    规则：
    1) pos_count 最大优先
    2) tokens 最大优先
    3) 若仍相同，随机选
    """
    if not entries:
        raise ValueError("entries is empty")

    max_pos = max(e.pos_count for e in entries)
    cands = [e for e in entries if e.pos_count == max_pos]

    max_tok = max(e.tokens for e in cands)
    cands2 = [e for e in cands if e.tokens == max_tok]

    return random.choice(cands2)


# =========================
# 写回策略
# =========================

def merge_fill_blanks(dst: Entry, src: Entry, fields: List[str]) -> Entry:
    """USE_CACHE：只填空，不覆盖已有值"""
    for f in fields:
        if f not in VALID_FIELDS:
            continue
        if _has_value(getattr(dst, f, None)):
            continue
        newv = getattr(src, f, None)
        if _has_value(newv):
            setattr(dst, f, newv)
    return dst


def overwrite_entry(dst: Entry, src: Entry) -> Entry:
    """FORCE_OVERWRITE：整条覆盖（保留 norm/original 标识的合理性）"""
    keep_norm = dst.word_norm or src.word_norm
    keep_original = dst.word_original or src.word_original

    out = Entry.from_dict(src.to_dict())
    out.word_norm = keep_norm
    out.word_original = keep_original
    return out


